CREATE TABLE fine_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fine_id BIGINT NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    reference_number VARCHAR(120),
    recorded_by BIGINT NOT NULL,
    paid_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_fine_payments_fine FOREIGN KEY (fine_id) REFERENCES fines (id),
    CONSTRAINT fk_fine_payments_recorded_by FOREIGN KEY (recorded_by) REFERENCES app_users (id),
    CONSTRAINT chk_fine_payments_amount CHECK (amount > 0),
    CONSTRAINT chk_fine_payments_method CHECK (payment_method IN ('CASH', 'CARD', 'BANK_TRANSFER'))
);

CREATE INDEX idx_fine_payments_fine_paid_at ON fine_payments (fine_id, paid_at);
