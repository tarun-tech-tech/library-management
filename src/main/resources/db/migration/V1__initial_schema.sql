CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(160) NOT NULL,
    email VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    member_id BIGINT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_app_users_username UNIQUE (username),
    CONSTRAINT uk_app_users_email UNIQUE (email),
    CONSTRAINT chk_app_users_role CHECK (role IN ('ADMIN', 'LIBRARIAN', 'MEMBER'))
);

CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(160) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(40),
    address VARCHAR(500),
    registration_date DATE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_members_email UNIQUE (email)
);

ALTER TABLE app_users
    ADD CONSTRAINT fk_app_users_member FOREIGN KEY (member_id) REFERENCES members (id);

CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(240) NOT NULL,
    author VARCHAR(180) NOT NULL,
    isbn VARCHAR(20) NOT NULL,
    category VARCHAR(120) NOT NULL,
    publisher VARCHAR(180),
    publication_year INTEGER,
    total_copies INTEGER NOT NULL DEFAULT 0,
    available_copies INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_books_isbn UNIQUE (isbn),
    CONSTRAINT chk_books_copies CHECK (total_copies >= 0 AND available_copies >= 0 AND available_copies <= total_copies),
    CONSTRAINT chk_books_publication_year CHECK (publication_year IS NULL OR publication_year BETWEEN 1000 AND 2200)
);

CREATE INDEX idx_books_title ON books (title);
CREATE INDEX idx_books_author ON books (author);
CREATE INDEX idx_books_category ON books (category);

CREATE TABLE book_copies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL,
    inventory_code VARCHAR(80) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',
    acquired_at DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uk_book_copies_inventory_code UNIQUE (inventory_code),
    CONSTRAINT fk_book_copies_book FOREIGN KEY (book_id) REFERENCES books (id),
    CONSTRAINT chk_book_copies_status CHECK (status IN ('AVAILABLE', 'LOANED', 'MAINTENANCE', 'LOST'))
);

CREATE INDEX idx_book_copies_book_status ON book_copies (book_id, status);

CREATE TABLE loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_copy_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    issue_date DATE NOT NULL,
    due_date DATE NOT NULL,
    returned_at DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'ISSUED',
    renewal_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_loans_book_copy FOREIGN KEY (book_copy_id) REFERENCES book_copies (id),
    CONSTRAINT fk_loans_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT chk_loans_status CHECK (status IN ('ISSUED', 'RETURNED')),
    CONSTRAINT chk_loans_renewal_count CHECK (renewal_count >= 0)
);

CREATE INDEX idx_loans_member_status ON loans (member_id, status);
CREATE INDEX idx_loans_due_date ON loans (due_date);

CREATE TABLE fines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id BIGINT NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    days_overdue INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'UNPAID',
    assessed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at TIMESTAMPTZ,
    CONSTRAINT uk_fines_loan UNIQUE (loan_id),
    CONSTRAINT fk_fines_loan FOREIGN KEY (loan_id) REFERENCES loans (id),
    CONSTRAINT chk_fines_amount CHECK (amount >= 0),
    CONSTRAINT chk_fines_days_overdue CHECK (days_overdue >= 0),
    CONSTRAINT chk_fines_status CHECK (status IN ('UNPAID', 'PAID'))
);

CREATE TABLE recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT,
    book_id BIGINT NOT NULL,
    score NUMERIC(8, 4) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_recommendations_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_recommendations_book FOREIGN KEY (book_id) REFERENCES books (id),
    CONSTRAINT chk_recommendations_score CHECK (score >= 0)
);

CREATE INDEX idx_recommendations_member_generated ON recommendations (member_id, generated_at);

CREATE TABLE spring_session (
    primary_id CHAR(36) NOT NULL,
    session_id CHAR(36) NOT NULL,
    creation_time BIGINT NOT NULL,
    last_access_time BIGINT NOT NULL,
    max_inactive_interval INTEGER NOT NULL,
    expiry_time BIGINT NOT NULL,
    principal_name VARCHAR(100),
    CONSTRAINT spring_session_pk PRIMARY KEY (primary_id)
);

CREATE UNIQUE INDEX spring_session_ix1 ON spring_session (session_id);
CREATE INDEX spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE spring_session_attributes (
    session_primary_id CHAR(36) NOT NULL,
    attribute_name VARCHAR(200) NOT NULL,
    attribute_bytes BYTEA NOT NULL,
    CONSTRAINT spring_session_attributes_pk PRIMARY KEY (session_primary_id, attribute_name),
    CONSTRAINT spring_session_attributes_fk FOREIGN KEY (session_primary_id)
        REFERENCES spring_session (primary_id) ON DELETE CASCADE
);
